"""Risk-evaluation definitions (Phase 5 §13–17).

This module is the single written source of truth for *what the numbers mean*.
Nothing here computes anything — it declares the evaluation protocol so the
metric code, the CLI, the documentation and the tests cannot drift apart.

Contents
--------
``PROTOCOL_VERSION``    version of the evaluation protocol itself.
``WINDOWS``             per-risk-type event window, lead window and the status
                        band that counts as "the required warning".
``SUFFICIENCY``         minimum sample sizes below which a metric is reported as
                        ``insufficient_data`` instead of a number.
``METRIC_DEFINITIONS``  plain-language definitions of every published metric.
``EVENT_WINDOW_NOTES``  per-risk-type prose that documents the window choice.

Event semantics
---------------
A **warning** is a persisted assessment whose ``status`` is in the risk type's
``warning_statuses`` band. Warnings are never deleted, but they may be
*superseded*; superseded rows still count, because a warning that was issued
was issued.

A **reference event** is a documented real-world occurrence (official rainfall
record, heat episode, dry spell, mandi price swing) with a district, a
timestamp and a source. Reference events are supplied by operators from
official datasets — never generated by this codebase.

Matching is performed at ``(risk_type, district)`` granularity, because
authoritative reference events (e.g. IMD district rainfall records) are
published per district while AGRIQ warnings are issued per field. When an
event names a crop and the warning recorded a crop, the crops must agree.

FALSE ALERT  — a warning was issued for ``(risk_type, district)`` and no
               reference event of that risk type was recorded for that
               district inside the risk type's ``false_alert_window_hours``
               after the warning.
MISSED EVENT — a reference event occurred and no qualifying warning (status in
               the required band) was issued for ``(risk_type, district)``
               inside the ``lead_window_hours`` before the event.
"""
from __future__ import annotations

from typing import Any, Mapping

PROTOCOL_VERSION = "agriq-risk-evaluation-v1"

#: Status bands that constitute "the required warning" per risk type. A
#: ``monitor`` reading is informational and deliberately NOT counted as a
#: warning: counting it would inflate recall and hide real missed events.
_DEFAULT_WARNING_STATUSES = ("elevated", "high", "critical")

WINDOWS: Mapping[str, Mapping[str, Any]] = {
    "disease_conducive_weather": {
        # Disease expression follows the conducive period by days, so a
        # warning stays falsifiable for 72 h and may be issued up to 48 h
        # ahead (the engine's disease screen uses a 24 h forecast horizon plus
        # the current observation).
        "false_alert_window_hours": 72,
        "lead_window_hours": 48,
        "warning_statuses": _DEFAULT_WARNING_STATUSES,
    },
    "heavy_rain_flooding": {
        # The engine screens a 3-day rainfall forecast and claims a 48 h lead.
        "false_alert_window_hours": 72,
        "lead_window_hours": 48,
        "warning_statuses": _DEFAULT_WARNING_STATUSES,
    },
    "heat_stress": {
        # The engine screens the next 48 h of daily maxima with a 24 h lead.
        "false_alert_window_hours": 48,
        "lead_window_hours": 48,
        "warning_statuses": _DEFAULT_WARNING_STATUSES,
    },
    "water_stress": {
        # Water stress accumulates over a dry spell the engine screens across
        # 7 forecast days, hence the longest windows in the protocol.
        "false_alert_window_hours": 120,
        "lead_window_hours": 120,
        "warning_statuses": _DEFAULT_WARNING_STATUSES,
    },
    "market_volatility": {
        # Descriptive, not a forecast: the engine claims no lead time, so only
        # a warning issued on the event day can be credited, and a warning is
        # judged against the 24 h that follow it.
        "false_alert_window_hours": 24,
        "lead_window_hours": 0,
        "warning_statuses": ("elevated", "high", "critical"),
    },
}

#: Minimum sample sizes. Below these, a metric is reported as
#: ``insufficient_data`` with the observed counts — never a number.
SUFFICIENCY: Mapping[str, int] = {
    "min_events": 10,           # reference events needed for outcome metrics
    "min_warning_windows": 10,  # falsifiable warning windows needed
    "min_calibration_samples": 30,  # paired (probability, outcome) points
    "min_lead_time_samples": 5,     # matched events needed for lead-time stats
}

METRIC_DEFINITIONS: Mapping[str, str] = {
    "precision": (
        "TP / (TP + FP) over falsifiable warning windows: of the warnings issued "
        "whose window has closed, the share followed by a recorded event."
    ),
    "recall": (
        "TP / (TP + FN) over reference events: of the documented events in scope, "
        "the share that received a qualifying warning inside the lead window."
    ),
    "f1": "Harmonic mean of precision and recall; reported only when both exist.",
    "false_alert_rate": (
        "FP / (TP + FP): share of falsifiable warning windows that closed with no "
        "recorded event. Complement of precision; reported separately because "
        "operators act on alert volume."
    ),
    "missed_event_rate": (
        "FN / (TP + FN): share of documented events that received no qualifying "
        "warning. Complement of recall."
    ),
    "brier_score": (
        "Mean squared error between the issued probability and the binary outcome "
        "(1 = event occurred inside the window, 0 = it did not). Lower is better. "
        "Computed over matched AND falsified warning windows."
    ),
    "reliability": (
        "Per-bin observed event frequency vs mean issued probability. Deviations "
        "wider than the documented tolerance mean the number must not be read as "
        "a calibrated probability."
    ),
    "warning_lead_time_hours": (
        "event_time - first_valid_warning_time, in hours, per matched event. "
        "Reported as count/mean/median/min/max plus a fixed-bucket distribution. "
        "No lead time is reported when no event was matched."
    ),
}

EVENT_WINDOW_NOTES: Mapping[str, str] = {
    "disease_conducive_weather": (
        "Reference event = a documented disease-conducive episode / confirmed "
        "outbreak window for the district. A warning is credited when issued "
        "within the 48 h before the episode start and is treated as a false alert "
        "if no episode is recorded in the 72 h after it. AGRIQ screens weather "
        "conditions, so the event definition must stay environmental, not "
        "diagnostic."
    ),
    "heavy_rain_flooding": (
        "Reference event = an official heavy-rainfall day (IMD conventional band: "
        ">= 64.5 mm/24 h) or a documented waterlogging/flood report for the "
        "district. Attribution of *flooding* to a single warning is only valid "
        "where the reference dataset records flooding explicitly; rainfall events "
        "alone must be reported as rainfall events."
    ),
    "heat_stress": (
        "Reference event = an official heat episode for the district (e.g. maximum "
        "temperature at or above the crop/stage screening limit used by the "
        "engine). Crop-specific limits differ, so events should carry the crop "
        "where the record allows it."
    ),
    "water_stress": (
        "Reference event = a documented dry spell (consecutive days with rainfall "
        "below the engine's meaningful-rain threshold) or an official drought "
        "advisory affecting the district. Soil moisture is not measured by AGRIQ, "
        "so a soil-moisture-based event definition is out of scope until a source "
        "exists."
    ),
    "market_volatility": (
        "Reference event = an official mandi modal-price swing beyond the engine's "
        "documented band, computed from the same official series. The engine makes "
        "no forecast, so no lead time can be credited and market results must not "
        "be presented as predictive performance."
    ),
}

#: Windows whose close is required before a warning can be judged. A warning
#: whose window has not closed yet is *pending* and excluded from precision and
#: false-alert rates — never counted as correct.
PENDING_NOTE = (
    "Warnings whose evaluation window has not yet closed are excluded from "
    "outcome metrics and reported as pending."
)


def window_for(risk_type: str) -> Mapping[str, Any] | None:
    """Return the documented window configuration for a risk type."""
    return WINDOWS.get(risk_type)


